#!/bin/bash
# Stage 3 pair: the learned transmission protocol vs the never-run no-comms
# control, both on the A7 substrate (arrival protections + tc-peer-zero live
# during training, which no previous RL run had), 8 workers each.
#
#   Arm A (comms):    learned message head, honest-beacon initialization,
#                     trunk-stopped supervision, overclaim penalty, belief-
#                     error sender credit -- the phase-168 machinery, now
#                     trained on the protected substrate.
#   Arm B (control):  identical except every comms knob off -- separates
#                     "fine-tune gain" from "channel gain" (phase 168 item 4:
#                     the control was never run).
#
# Success bar: A's comms-ON eval beats A's comms-OFF eval and both beat the
# A7 full-matrix baseline (t8k 0.671 +- 0.015 over 4 cells, t4k 0.304).
# Usage: train_rl_s3_pair.sh <iterations> <out_root>
set -o errexit
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY_DIR="$(dirname "$SCRIPT_DIR")"
REPO="$(dirname "$PY_DIR")"
cd "$PY_DIR"

ITERATIONS="${1:-100}"
OUT="${2:-$REPO/results/rl_s3}"
mkdir -p "$OUT/comms" "$OUT/control"

# Arm A: the learned channel
KILOBOT_INIT_ACTOR="$REPO/results/bc_v2/run_r0/actor_best.pt" \
KILOBOT_MODE=rl \
KILOBOT_SMOKE=0 \
KILOBOT_ITERATIONS="$ITERATIONS" \
KILOBOT_NUM_WORKERS=8 \
KILOBOT_DEVICE=cuda \
KILOBOT_ACTOR_TYPE=gru_split_observation \
KILOBOT_SPLIT_ACTIVATION=elu \
KILOBOT_USE_ARRIVED_HEAD=1 \
KILOBOT_USE_TURN_ANCHOR=1 \
KILOBOT_USE_STATE_HEAD=1 \
